class TestPostgresDialectAndBackendControl(unittest.TestCase):
    def test_sql_dialect_translation_ddl_dml_glob_minmax_and_floor_cast(self) -> None:
        ddl_sql, auto_ret = translate_sqlite_to_postgres_sql(
            "CREATE TABLE IF NOT EXISTS rank_snapshots (id INTEGER PRIMARY KEY AUTOINCREMENT, ts REAL NOT NULL, pts INTEGER NOT NULL)",
            False,
        )
        self.assertFalse(auto_ret)
        self.assertIn("BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", ddl_sql)
        self.assertIn("DOUBLE PRECISION NOT NULL", ddl_sql)
        self.assertIn("pts BIGINT NOT NULL", ddl_sql)

        ins_ign, auto_ret2 = translate_sqlite_to_postgres_sql(
            "INSERT OR IGNORE INTO hourly_production_history(minute_bucket, recorded_at) VALUES (?, ?)",
            True,
        )
        self.assertFalse(auto_ret2)
        self.assertTrue(ins_ign.startswith("INSERT INTO hourly_production_history"))
        self.assertTrue(ins_ign.endswith("ON CONFLICT DO NOTHING"))
        self.assertEqual(ins_ign.count("%s"), 2)

        plain_ins, auto_ret3 = translate_sqlite_to_postgres_sql(
            "INSERT INTO manual_queue(created_ts, updated_ts, kind) VALUES (?, ?, ?)",
            True,
        )
        self.assertTrue(auto_ret3)
        self.assertTrue(plain_ins.endswith("RETURNING id"))

        upsert_minmax, _ = translate_sqlite_to_postgres_sql(
            "INSERT INTO spy_targets(coords, last_scanned_ts) VALUES (?, ?) "
            "ON CONFLICT(coords) DO UPDATE SET last_scanned_ts = MAX(spy_targets.last_scanned_ts, excluded.last_scanned_ts)",
            True,
        )
        self.assertIn("GREATEST(spy_targets.last_scanned_ts, excluded.last_scanned_ts)", upsert_minmax)

        agg_max, _ = translate_sqlite_to_postgres_sql(
            "SELECT MAX(ts), MIN(ts) FROM spy_reports WHERE target_coords = ? AND msg_uid NOT LIKE 'id:msg-%'",
            True,
        )
        self.assertIn("MAX(ts)", agg_max)
        self.assertIn("MIN(ts)", agg_max)
        self.assertIn("'id:msg-%%'", agg_max)

        glob_sql, _ = translate_sqlite_to_postgres_sql(
            "SELECT category, COUNT(*) AS cnt FROM game_messages WHERE msg_uid NOT LIKE 'id:msg-%' AND TRIM(body_text) NOT GLOB '[0-9]* / [0-9]*' GROUP BY category",
            False,
        )
        self.assertIn("!~ '^[0-9].* / [0-9].*$'", glob_sql)
        self.assertIn("'id:msg-%'", glob_sql)

        cast_sql, _ = translate_sqlite_to_postgres_sql(
            "SELECT CAST(ts / 3600 AS INTEGER) * 3600 AS hour_bucket FROM battle_reports",
            False,
        )
        self.assertIn("CAST(FLOOR(ts / 3600) AS BIGINT) * 3600", cast_sql)

    def test_postgres_row_dual_positional_and_mapping_semantics(self) -> None:
        row = PostgresRow((42, "02:380:12", "#PP Planet"), ("id", "coords", "name"), {"id": 0, "coords": 1, "name": 2})
        self.assertEqual(row[0], 42)
        self.assertEqual(row["coords"], "02:380:12")
        self.assertEqual(dict(row), {"id": 42, "coords": "02:380:12", "name": "#PP Planet"})
        a, b, c = row
        self.assertEqual((a, b, c), (42, "02:380:12", "#PP Planet"))

    def test_backend_config_precedence_persistence_and_url_redaction(self) -> None:
        self.assertEqual(
            redact_db_url("postgresql://spaceinvasion:supersecret@127.0.0.1:5433/spaceinvasion"),
            "postgresql://spaceinvasion:***@127.0.0.1:5433/spaceinvasion",
        )
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            # Host default (outside Docker) resolves to sqlite
            cfg_def = resolve_database_config(root_dir=root, env={})
            self.assertEqual(cfg_def.backend, "sqlite")
            self.assertEqual(cfg_def.selection_source, "default")

            # Docker / Podman container mode forces postgres exclusively
            cfg_container = resolve_database_config(
                root_dir=root,
                env={"SPACEINVASION_CONTAINER": "1"},
            )
            self.assertEqual(cfg_container.backend, "postgres")
            self.assertEqual(cfg_container.selection_source, "container_postgres_only")
            with self.assertRaises(ValueError):
                resolve_database_config(
                    explicit_backend="sqlite",
                    root_dir=root,
                    env={"SPACEINVASION_CONTAINER": "1"},
                )

            # Persisted preference in isolated temp root
            save_persisted_db_preference("postgres", root_dir=root)
            cfg_pref = resolve_database_config(root_dir=root, env={})
            self.assertEqual(cfg_pref.backend, "postgres")
            self.assertEqual(cfg_pref.selection_source, "persisted_preference")

            # Env var overrides persisted preference
            cfg_env = resolve_database_config(
                root_dir=root,
                env={"SPACEINVASION_DB_BACKEND": "postgres"},
            )
            self.assertEqual(cfg_env.backend, "postgres")
            self.assertEqual(cfg_env.selection_source, "env_var")

            # CLI flag overrides env var
            cfg_cli = resolve_database_config(
                explicit_backend="sqlite",
                root_dir=root,
                env={"SPACEINVASION_DB_BACKEND": "postgres"},
            )
            self.assertEqual(cfg_cli.backend, "sqlite")
            self.assertEqual(cfg_cli.selection_source, "cli_flag")

    def test_postgres_podman_migrations_concurrent_mvcc_sync_and_live_bridge_switch(self) -> None:
        base_dsn = build_default_postgres_url()
        ok, _ms, _msg = ping_postgres(base_dsn, timeout=1.5)
        if not ok:
            self.skipTest("Local Podman PostgreSQL container is not running on configured port.")

        import psycopg
        from urllib.parse import urlparse, urlunparse

        parsed = urlparse(base_dsn)
        admin_dsn = urlunparse((parsed.scheme, parsed.netloc, "/postgres", "", "", ""))
        test_db_name = "si_unit_pg_test"
        test_dsn = urlunparse((parsed.scheme, parsed.netloc, f"/{test_db_name}", "", "", ""))

        with psycopg.connect(admin_dsn, autocommit=True) as aconn:
            aconn.execute(f"DROP DATABASE IF EXISTS {test_db_name}")
            aconn.execute(f"CREATE DATABASE {test_db_name}")

        try:
            pg_db = GameDatabase(test_dsn, backend="postgres")
            try:
                self.assertEqual(pg_db.backend_name, "postgres")
                ver = pg_db.verify_schema(full_integrity=True)
                self.assertTrue(ver["ok"])
                self.assertEqual(ver["version"], LATEST_SCHEMA_VERSION)

                planet = PlanetState(
                    planet_id=12476,
                    name="Colony",
                    coords="02:380:12",
                    planet_type="normal",
                    temperature=28,
                    fields_used=45,
                    fields_max=310,
                    resources=Resources(50000, 30000, 20000, 10000),
                    storage=Resources(500000, 500000, 500000, 500000),
                    energy=EnergyBalance(800, 500),
                    buildings={"b1": 15, "b2": 12, "b3": 14, "b4": 10, "b5": 16},
                )
                state = GameState(
                    universe_id=31,
                    user_id=103603,
                    nickname="tester",
                    timestamp=time.time(),
                    planets=(planet,),
                    active_planet_id=12476,
                    researches={"r1": 5},
                )
                pg_db.record_state_snapshot(state)
                pg_db.record_full_state_snapshot(state, [], source="test")
                pg_db.record_galaxy_scan(
                    2,
                    380,
                    [
                        GalaxySlot(
                            position=4,
                            coords="02:380:04",
                            name="Farm",
                            owner="InactivePlayer",
                            status_color="yellow",
                            has_debris=True,
                        ),
                        GalaxySlot(
                            position=8,
                            coords="02:380:08",
                            name="",
                            owner="",
                            status_color="free",
                            has_debris=False,
                            colonize_min_fields=290,
                            colonize_max_fields=335,
                            temperature=22,
                        ),
                    ],
                )
                pg_db.record_spy_report(
                    SpyReport(
                        target_coords="02:380:04",
                        owner="InactivePlayer",
                        planet_name="Farm",
                        is_spacia=False,
                        resources=Resources(100000, 80000, 60000, 40000),
                        buildings={"b1": 20},
                        fleet={},
                        defense={},
                        researches={},
                    )
                )
                pg_db.set_custom_planet_name(12476, "#PP Planet")
                q1 = pg_db.enqueue_manual_command(
                    kind="UPGRADE_BUILDING",
                    priority="P1",
                    planet_id=12476,
                    planet_coords="02:380:12",
                    target_id=1,
                    target_name="Pig iron mine",
                    target_level=16,
                )
                self.assertGreaterEqual(q1["id"], 1)

                # Verify concurrent MVCC reads & writes across multiple threads without contention errors
                errors: list[Exception] = []

                def _worker(idx: int) -> None:
                    try:
                        for _ in range(5):
                            pg_db.record_hourly_production(1000 + idx, 800, 600, 400, 2800, 750, 1, 1)
                            _ = pg_db.summary()
                            _ = pg_db.get_spy_targets(limit=10)
                    except Exception as exc:
                        errors.append(exc)

                threads = [threading.Thread(target=_worker, args=(i,)) for i in range(4)]
                for t in threads:
                    t.start()
                for t in threads:
                    t.join(timeout=10.0)
                self.assertEqual(errors, [])

                with tempfile.TemporaryDirectory() as td:
                    td_path = Path(td)
                    bkp = pg_db.create_backup(label="unit_pg", backup_dir=td_path / "backups")
                    self.assertTrue(bkp["ok"])
                    self.assertTrue(Path(bkp["backup_path"]).exists())

                    # Sync Postgres -> SQLite and verify live GameApiBridge switch_db_backend
                    sqlite_file = td_path / "mirror.db"
                    sq_db = GameDatabase(sqlite_file, attack_history_path="")
                    try:
                        sync_to_sq = sync_database_stores(pg_db, sq_db)
                        self.assertTrue(sync_to_sq["ok"])
                        self.assertEqual(sq_db.get_custom_planet_names()["12476"], "#PP Planet")
                        q2 = sq_db.enqueue_manual_command(
                            kind="RESEARCH",
                            priority="P2",
                            planet_id=12476,
                            planet_coords="02:380:12",
                            target_id=1,
                            target_name="Mining technology",
                            target_level=6,
                        )
                    finally:
                        sq_db.close()

                    fake_client = MagicMock()
                    fake_client.__enter__.return_value = fake_client
                    fake_client.driver = MagicMock(current_url="https://spaceinvasion.bitmeup.com/indexGame.es")
                    fake_client.read_full_snapshot.return_value = state
                    bridge_sq = GameApiBridge(
                        debug_port=19999,
                        env_file=td_path / "no.env",
                        db_path=sqlite_file,
                        log_dir=None,
                        client_factory=lambda _port: fake_client,
                        ensure_session_fn=lambda: None,
                    )
                    try:
                        st0 = bridge_sq.handle_command({"command": "db_backend_status"})
                        self.assertEqual(st0["db_backend"]["backend"], "sqlite")
                    finally:
                        bridge_sq.close()

                    # Verify sync_database_stores SQLite -> Postgres advances identity sequence past q2["id"]
                    sq_db2 = GameDatabase(sqlite_file, attack_history_path="")
                    try:
                        sync_to_pg = sync_database_stores(sq_db2, pg_db)
                        self.assertTrue(sync_to_pg["ok"])
                    finally:
                        sq_db2.close()

                    bridge_pg = GameApiBridge(
                        debug_port=19999,
                        env_file=td_path / "no.env",
                        db_path=test_dsn,
                        log_dir=None,
                        client_factory=lambda _port: fake_client,
                        ensure_session_fn=lambda: None,
                    )
                    try:
                        st_pg = bridge_pg.handle_command({"command": "db_backend_status"})
                        self.assertEqual(st_pg["db_backend"]["backend"], "postgres")
                        assert bridge_pg._db is not None
                        q3 = bridge_pg._db.enqueue_manual_command(
                            kind="BUILD_SHIP",
                            priority="P3",
                            planet_id=12476,
                            planet_coords="02:380:12",
                            target_id=10,
                            target_name="Small transporter",
                            target_level=5,
                        )
                        self.assertGreater(q3["id"], q2["id"])
                        self.assertEqual(len(bridge_pg._db.get_manual_queue()), 3)
                    finally:
                        bridge_pg.close()
            finally:
                pg_db.close()
        finally:
            with psycopg.connect(admin_dsn, autocommit=True) as aconn:
                aconn.execute(f"DROP DATABASE IF EXISTS {test_db_name}")


if __name__ == "__main__":
    unittest.main()
