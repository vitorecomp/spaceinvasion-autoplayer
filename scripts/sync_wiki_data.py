def write_catalog_tables(payload: dict[str, Any], tables_dir: Path = OUTPUT_TABLES_DIR) -> None:
    """Write scraped SpaceInvasion Classic tables into ``backend/core/catalog/tables/*.json``."""
    tables_dir.mkdir(parents=True, exist_ok=True)
    for filename, key in (
        ("buildings.json", "buildings"),
        ("research.json", "researches"),
        ("ships.json", "ships"),
        ("defenses.json", "defenses"),
    ):
        (tables_dir / filename).write_text(
            json.dumps(payload[key], indent=2, ensure_ascii=False, allow_nan=False) + "\n",
            encoding="utf-8",
        )


def main() -> int:
    parser = argparse.ArgumentParser(description="Sync SpaceInvasion Classic Wiki data into catalog tables JSON")
    parser.add_argument("--output-dir", type=Path, default=OUTPUT_TABLES_DIR)
    args = parser.parse_args()
    payload = scrape_wiki()
    write_catalog_tables(payload, args.output_dir)
    sys.stdout.write(
        f"Wrote {args.output_dir}: {len(payload['buildings'])} buildings, "
        f"{len(payload['researches'])} researches, {len(payload['ships'])} ships, "
        f"{len(payload['defenses'])} defenses\n"
    )
    return 0


