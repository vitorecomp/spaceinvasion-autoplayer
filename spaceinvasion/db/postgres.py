class PostgresRow(Sequence[Any]):
    """Lightweight `sqlite3.Row`-compatible row supporting `r[0]`, `r['col']`, `r.keys()`, and `dict(r)`."""

    __slots__ = ("_values", "_cols", "_idx")

    def __init__(
        self,
        values: tuple[Any, ...],
        cols: tuple[str, ...],
        col_index: dict[str, int],
    ) -> None:
        self._values = values
        self._cols = cols
        self._idx = col_index

    def __getitem__(self, key: int | slice | str) -> Any:
        if type(key) is int:
            return self._values[key]
        if type(key) is str:
            try:
                return self._values[self._idx[key]]
            except KeyError as exc:
                raise IndexError(f"No item with that key: {key!r}") from exc
        if isinstance(key, slice):
            return self._values[key]
        if isinstance(key, int):
            return self._values[int(key)]
        raise TypeError(f"Row indices must be integers, slices, or strings, not {type(key).__name__}")

    def __len__(self) -> int:
        return len(self._values)

    def __iter__(self) -> Iterator[Any]:
        return iter(self._values)

    def __contains__(self, item: object) -> bool:
        if isinstance(item, str):
            return item in self._idx
        return item in self._values

    def keys(self) -> list[str]:
        return list(self._cols)

    def get(self, key: str, default: Any = None) -> Any:
        pos = self._idx.get(key)
        return self._values[pos] if pos is not None else default

    def __repr__(self) -> str:
        pairs = ", ".join(f"{k}={v!r}" for k, v in zip(self._cols, self._values))
        return f"PostgresRow({pairs})"


def _lex_sql(sql: str) -> list[tuple[str, str]]:
    """Tokenize SQL into ('code' | 'squote' | 'dquote' | 'lcomment' | 'bcomment', segment) pairs."""
    out: list[tuple[str, str]] = []
    n = len(sql)
    i = 0
    code_start = 0

    while i < n:
        ch = sql[i]
        nxt = sql[i + 1] if i + 1 < n else ""

        if ch == "-" and nxt == "-":
            if i > code_start:
                out.append(("code", sql[code_start:i]))
            j = sql.find("\n", i + 2)
            end = n if j < 0 else j + 1
            out.append(("lcomment", sql[i:end]))
            i = end
            code_start = i
            continue

        if ch == "/" and nxt == "*":
            if i > code_start:
                out.append(("code", sql[code_start:i]))
            j = sql.find("*/", i + 2)
            end = n if j < 0 else j + 2
            out.append(("bcomment", sql[i:end]))
            i = end
            code_start = i
            continue

        if ch == "'":
            if i > code_start:
                out.append(("code", sql[code_start:i]))
            j = i + 1
            while j < n:
                if sql[j] == "'":
                    if j + 1 < n and sql[j + 1] == "'":
                        j += 2
                        continue
                    j += 1
                    break
                j += 1
            out.append(("squote", sql[i:j]))
            i = j
            code_start = i
            continue

        if ch == '"':
            if i > code_start:
                out.append(("code", sql[code_start:i]))
            j = i + 1
            while j < n:
                if sql[j] == '"':
                    if j + 1 < n and sql[j + 1] == '"':
                        j += 2
                        continue
                    j += 1
                    break
                j += 1
            out.append(("dquote", sql[i:j]))
            i = j
            code_start = i
            continue

        i += 1

    if code_start < n:
        out.append(("code", sql[code_start:n]))
    return out


def _rewrite_scalar_minmax(sql: str) -> str:
    """Rewrite 2-argument scalar `MAX(a, b)` -> `GREATEST(a, b)` and `MIN(a, b)` -> `LEAST(a, b)`.

    Leaves 1-argument aggregate `MAX(col)` / `MIN(col)` and quoted literals untouched.
    """
    tokens = _lex_sql(sql)
    if not any(k == "code" and re.search(r"\b(?:MAX|MIN)\s*\(", seg, re.IGNORECASE) for k, seg in tokens):
        return sql

    pattern = re.compile(r"\b(MAX|MIN)\s*\(", re.IGNORECASE)
    pos = 0
    pieces: list[str] = []
    n = len(sql)
    # Build quote/comment spans so we never match `MAX(...)` inside literals or comments
    non_code_spans: list[tuple[int, int]] = []
    off = 0
    for k, seg in tokens:
        nxt_off = off + len(seg)
        if k != "code":
            non_code_spans.append((off, nxt_off))
        off = nxt_off

    def _in_non_code(idx: int) -> Optional[int]:
        for s_i, e_i in non_code_spans:
            if s_i <= idx < e_i:
                return e_i
        return None

    while pos < n:
        m = pattern.search(sql, pos)
        if m is None:
            pieces.append(sql[pos:])
            break
        skip_to = _in_non_code(m.start())
        if skip_to is not None:
            pieces.append(sql[pos:skip_to])
            pos = skip_to
            continue
        pieces.append(sql[pos : m.start()])
        fn_upper = m.group(1).upper()
        open_paren = m.end() - 1
        depth = 1
        k = open_paren + 1
        in_sq = False
        in_dq = False
        top_commas = 0
        while k < n and depth > 0:
            c = sql[k]
            if in_sq:
                if c == "'":
                    if k + 1 < n and sql[k + 1] == "'":
                        k += 2
                        continue
                    in_sq = False
            elif in_dq:
                if c == '"':
                    if k + 1 < n and sql[k + 1] == '"':
                        k += 2
                        continue
                    in_dq = False
            else:
                if c == "'":
                    in_sq = True
                elif c == '"':
                    in_dq = True
                elif c == "(":
                    depth += 1
                elif c == ")":
                    depth -= 1
                    if depth == 0:
                        break
                elif c == "," and depth == 1:
                    top_commas += 1
            k += 1

        if depth == 0 and top_commas >= 1:
            replacement_fn = "GREATEST" if fn_upper == "MAX" else "LEAST"
            inner = _rewrite_scalar_minmax(sql[open_paren + 1 : k])
            pieces.append(f"{replacement_fn}({inner})")
            pos = k + 1
        else:
            pieces.append(sql[m.start() : open_paren + 1])
            pos = open_paren + 1
    return "".join(pieces)


@functools.lru_cache(maxsize=2048)
def translate_sqlite_to_postgres_sql(sql: str, has_params: bool) -> tuple[str, bool]:
    """Translate a single SQLite SQL statement into PostgreSQL 16 SQL.

    Returns `(pg_sql, auto_returning_id)` where `auto_returning_id=True` indicates
    `RETURNING id` was appended automatically to populate `cursor.lastrowid`.
    """
    stripped = sql.strip().rstrip(";").strip()
    if not stripped:
        return ("", False)

    upper_head = stripped[:48].upper()
    is_ddl = upper_head.startswith("CREATE TABLE") or upper_head.startswith("ALTER TABLE")

    tokens = _lex_sql(stripped)
    insert_or_ignore = False
    rebuilt: list[str] = []

    for idx, (kind, seg) in enumerate(tokens):
        if kind != "code":
            # Special-case SQLite `NOT GLOB '[0-9]* / [0-9]*'` literal right after GLOB rewrite
            rebuilt.append(seg.replace("%", "%%") if has_params else seg)
            continue

        code = seg
        if has_params:
            code = code.replace("%", "%%").replace("?", "%s")

        if re.search(r"\bINSERT\s+OR\s+IGNORE\s+INTO\b", code, re.IGNORECASE):
            code = re.sub(r"\bINSERT\s+OR\s+IGNORE\s+INTO\b", "INSERT INTO", code, flags=re.IGNORECASE)
            insert_or_ignore = True

        # PostgreSQL `CAST(double_precision AS BIGINT)` rounds to nearest even instead of truncating;
        # preserve SQLite `CAST(ts / 3600 AS INTEGER)` floor semantics for positive epoch timestamps.
        code = re.sub(
            r"\bCAST\s*\(\s*([A-Za-z_][A-Za-z0-9_.]*\s*/\s*\d+(?:\.\d+)?)\s+AS\s+INTEGER\s*\)",
            r"CAST(FLOOR(\1) AS BIGINT)",
            code,
            flags=re.IGNORECASE,
        )

        # Strip SQLite dynamic-affinity `AND <numeric_col> != ''` guards on typed BIGINT/FLOAT8 columns
        if idx + 1 < len(tokens) and tokens[idx + 1] == ("squote", "''"):
            if re.search(
                r"\bAND\s+(?:is_inactive|is_spacia|last_spied_ts|pig_iron|metal|kryptonite|spice)\s*!=\s*$",
                code,
                re.IGNORECASE,
            ):
                code = re.sub(
                    r"\s*\bAND\s+(?:is_inactive|is_spacia|last_spied_ts|pig_iron|metal|kryptonite|spice)\s*!=\s*$",
                    "",
                    code,
                    flags=re.IGNORECASE,
                )
                tokens[idx + 1] = ("code", "")

        # Rewrite `NOT GLOB` when followed by `'[0-9]* / [0-9]*'`
        if idx + 1 < len(tokens) and tokens[idx + 1][0] == "squote":
            if re.search(r"\bNOT\s+GLOB\s*$", code, re.IGNORECASE) and tokens[idx + 1][1] == "'[0-9]* / [0-9]*'":
                code = re.sub(r"\bNOT\s+GLOB\s*$", "!~ ", code, flags=re.IGNORECASE)
                tokens[idx + 1] = ("squote", "'^[0-9].* / [0-9].*$'")

        if is_ddl:
            code = re.sub(
                r"\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b",
                "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
                code,
                flags=re.IGNORECASE,
            )
            code = re.sub(r"\bINTEGER\b", "BIGINT", code, flags=re.IGNORECASE)
            code = re.sub(r"\bREAL\b", "DOUBLE PRECISION", code, flags=re.IGNORECASE)

        rebuilt.append(code)

    joined = "".join(rebuilt)
    if "MAX" in joined.upper() or "MIN" in joined.upper():
        # Only rewrite outside string literals: re-lex and apply if top-level commas exist
        joined = _rewrite_scalar_minmax(joined)

    if insert_or_ignore and not re.search(r"\bON\s+CONFLICT\b", joined, re.IGNORECASE):
        joined = f"{joined} ON CONFLICT DO NOTHING"

    auto_returning_id = False
    m_ins = _PLAIN_INSERT_INTO_RE.match(joined)
    if m_ins is not None:
        tbl_lower = m_ins.group(1).lower()
        if (
            tbl_lower in IDENTITY_ID_TABLES
            and not re.search(r"\bRETURNING\b", joined, re.IGNORECASE)
            and not re.search(r"\bON\s+CONFLICT\b", joined, re.IGNORECASE)
        ):
            joined = f"{joined} RETURNING id"
            auto_returning_id = True

    return (joined, auto_returning_id)


def _adapt_param_value(val: Any) -> Any:
    if isinstance(val, bool):
        return 1 if val else 0
    return val


def _adapt_params(params: Optional[Sequence[Any]]) -> Optional[tuple[Any, ...]]:
    if params is None:
        return None
    seq = tuple(_adapt_param_value(v) for v in params)
    return seq if len(seq) > 0 else None


def _wrap_pg_error(exc: BaseException) -> sqlite3.DatabaseError:
    if isinstance(exc, sqlite3.DatabaseError):
        return exc
    if isinstance(exc, psycopg.IntegrityError):
        return sqlite3.IntegrityError(str(exc))
    if isinstance(exc, psycopg.OperationalError):
        return sqlite3.OperationalError(str(exc))
    return sqlite3.DatabaseError(str(exc))


class PostgresCursorResult:
    """`sqlite3.Cursor`-compatible result wrapper around fetched rows or a live `PostgresSession`."""

    __slots__ = ("_rows", "_pos", "rowcount", "lastrowid", "row_factory", "_session")

    def __init__(
        self,
        rows: list[Any],
        *,
        rowcount: int = -1,
        lastrowid: Optional[int] = None,
        row_factory: Any = PostgresRow,
        session: Optional["PostgresSession"] = None,
    ) -> None:
        self._rows = rows
        self._pos = 0
        self.rowcount = rowcount
        self.lastrowid = lastrowid
        self.row_factory = row_factory
        self._session = session

    def execute(self, sql: str, params: Optional[Sequence[Any]] = None) -> "PostgresCursorResult":
        if self._session is None:
            raise sqlite3.ProgrammingError("Cursor has no bound session.")
        res = self._session.execute(sql, params, use_row_factory=(self.row_factory is not None))
        self._rows = res._rows
        self._pos = 0
        self.rowcount = res.rowcount
        self.lastrowid = res.lastrowid
        return self

    def executemany(self, sql: str, seq_of_params: Iterable[Sequence[Any]]) -> "PostgresCursorResult":
        if self._session is None:
            raise sqlite3.ProgrammingError("Cursor has no bound session.")
        res = self._session.executemany(sql, seq_of_params)
        self._rows = []
        self._pos = 0
        self.rowcount = res.rowcount
        self.lastrowid = None
        return self

    def fetchone(self) -> Any:
        if self._pos >= len(self._rows):
            return None
        val = self._rows[self._pos]
        self._pos += 1
        return val

    def fetchall(self) -> list[Any]:
        if self._pos == 0:
            self._pos = len(self._rows)
            return list(self._rows)
        rem = self._rows[self._pos :]
        self._pos = len(self._rows)
        return list(rem)

    def fetchmany(self, size: int = 100) -> list[Any]:
        end = min(len(self._rows), self._pos + max(1, int(size)))
        chunk = self._rows[self._pos : end]
        self._pos = end
        return list(chunk)

    def __iter__(self) -> Iterator[Any]:
        while self._pos < len(self._rows):
            yield self._rows[self._pos]
            self._pos += 1

    def close(self) -> None:
        self._rows = []
        self._pos = 0


class PostgresSession:
    """Single checked-out PostgreSQL connection wrapper implementing `sqlite3.Connection` methods."""

    def __init__(self, backend: "PostgresPoolBackend", raw_conn: psycopg.Connection[Any]) -> None:
        self._backend = backend
        self._raw = raw_conn
        self.row_factory: Any = PostgresRow
        self._dirty_writes = 0
        self._savepoints: list[str] = []

    @property
    def in_transaction(self) -> bool:
        return self._raw.info.transaction_status in (
            pq.TransactionStatus.INTRANS,
            pq.TransactionStatus.INERROR,
        )

    @property
    def total_changes(self) -> int:
        return self._backend.total_changes

    def cursor(self) -> PostgresCursorResult:
        return PostgresCursorResult([], row_factory=self.row_factory, session=self)

    def _build_rows(
        self,
        raw_rows: Sequence[tuple[Any, ...]],
        col_names: tuple[str, ...],
        *,
        use_row_factory: bool,
    ) -> list[Any]:
        if not raw_rows:
            return []
        if not use_row_factory or self.row_factory is None:
            return [tuple(r) for r in raw_rows]
        col_idx = {name: idx for idx, name in enumerate(col_names)}
        return [PostgresRow(tuple(r), col_names, col_idx) for r in raw_rows]

    def execute(
        self,
        sql: str,
        params: Optional[Sequence[Any]] = None,
        *,
        use_row_factory: Optional[bool] = None,
    ) -> PostgresCursorResult:
        want_rows = (self.row_factory is not None) if use_row_factory is None else bool(use_row_factory)
        s = sql.strip()
        if not s:
            return PostgresCursorResult([], rowcount=0, row_factory=self.row_factory, session=self)

        # 1. PRAGMA & sqlite_master intercepts
        if _PRAGMA_NOOP_RE.match(s):
            return PostgresCursorResult(
                self._build_rows([("ok",)], ("status",), use_row_factory=want_rows),
                rowcount=0,
                session=self,
            )

        if _PRAGMA_DATA_VER_RE.match(s):
            dv = self._backend.get_data_version(self._raw)
            return PostgresCursorResult(
                self._build_rows([(dv,)], ("data_version",), use_row_factory=want_rows),
                rowcount=1,
                session=self,
            )

        if _PRAGMA_USER_VER_GET_RE.match(s):
            uv = self._read_user_version()
            return PostgresCursorResult(
                self._build_rows([(uv,)], ("user_version",), use_row_factory=want_rows),
                rowcount=1,
                session=self,
            )

        m_uv_set = _PRAGMA_USER_VER_SET_RE.match(s)
        if m_uv_set is not None:
            uv_val = int(m_uv_set.group(1))
            self._write_user_version(uv_val)
            return PostgresCursorResult([], rowcount=1, session=self)

        m_chk = _PRAGMA_CHECK_RE.match(s)
        if m_chk is not None:
            msgs = self._run_integrity_check(full=(m_chk.group(1).lower() == "integrity_check"))
            return PostgresCursorResult(
                self._build_rows([(msg,) for msg in msgs], ("integrity_check",), use_row_factory=want_rows),
                rowcount=len(msgs),
                session=self,
            )

        m_ti = _PRAGMA_TABLE_INFO_RE.match(s)
        if m_ti is not None:
            tbl = m_ti.group(1)
            info_rows = self._read_table_info(tbl)
            return PostgresCursorResult(
                self._build_rows(
                    info_rows,
                    ("cid", "name", "type", "notnull", "dflt_value", "pk"),
                    use_row_factory=want_rows,
                ),
                rowcount=len(info_rows),
                session=self,
            )

        m_sm_one = _SQLITE_MASTER_ONE_RE.match(s)
        if m_sm_one is not None:
            arg_tok = m_sm_one.group(1)
            if arg_tok == "?":
                tbl_arg = str(params[0]) if params else ""
            else:
                tbl_arg = arg_tok.strip("'")
            exists = self._table_exists(tbl_arg)
            raw_res = [(1,)] if exists else []
            return PostgresCursorResult(
                self._build_rows(raw_res, ("exists",), use_row_factory=want_rows),
                rowcount=len(raw_res),
                session=self,
            )

        if _SQLITE_MASTER_ALL_RE.match(s):
            names = self._list_tables()
            return PostgresCursorResult(
                self._build_rows([(n,) for n in names], ("name",), use_row_factory=want_rows),
                rowcount=len(names),
                session=self,
            )

        # 2. Track SAVEPOINT lifecycle so error recovery knows whether nested savepoints are active
        m_sp_start = _SAVEPOINT_START_RE.match(s)
        m_sp_rel = _SAVEPOINT_RELEASE_RE.match(s)
        m_sp_rb = _SAVEPOINT_ROLLBACK_RE.match(s)

        adapted_params = _adapt_params(params)
        has_p = adapted_params is not None
        pg_sql, auto_ret_id = translate_sqlite_to_postgres_sql(s, has_p)

        try:
            with self._raw.cursor() as cur:
                if has_p:
                    cur.execute(pg_sql, adapted_params)
                else:
                    cur.execute(pg_sql)

                rc = int(cur.rowcount) if cur.rowcount is not None and cur.rowcount >= 0 else 0
                last_id: Optional[int] = None
                fetched: list[tuple[Any, ...]] = []
                col_names: tuple[str, ...] = ()

                if cur.description is not None:
                    col_names = tuple(col.name for col in cur.description)
                    fetched = cur.fetchall()
                    if auto_ret_id:
                        if fetched and fetched[0] and fetched[0][0] is not None:
                            last_id = int(fetched[0][0])
                        fetched = []
                        col_names = ()

                if m_sp_start is not None:
                    self._savepoints.append(m_sp_start.group(1))
                elif m_sp_rel is not None:
                    sp_nm = m_sp_rel.group(1)
                    if sp_nm in self._savepoints:
                        idx = len(self._savepoints) - 1 - self._savepoints[::-1].index(sp_nm)
                        del self._savepoints[idx:]
                elif m_sp_rb is not None:
                    pass
                elif _WRITE_VERB_RE.match(pg_sql):
                    self._dirty_writes += max(1, rc)
                    self._backend.bump_local_changes(max(1, rc))

                return PostgresCursorResult(
                    self._build_rows(fetched, col_names, use_row_factory=want_rows),
                    rowcount=rc,
                    lastrowid=last_id,
                    row_factory=self.row_factory,
                    session=self,
                )
        except Exception as exc:
            if (
                self._raw.info.transaction_status == pq.TransactionStatus.INERROR
                and not self._savepoints
                and self._dirty_writes == 0
            ):
                with contextlib.suppress(Exception):
                    self._raw.rollback()
            raise _wrap_pg_error(exc) from exc

    def executemany(self, sql: str, seq_of_params: Iterable[Sequence[Any]]) -> PostgresCursorResult:
        param_list = [_adapt_params(p) or () for p in seq_of_params]
        if not param_list:
            return PostgresCursorResult([], rowcount=0, row_factory=self.row_factory, session=self)
        pg_sql, _ = translate_sqlite_to_postgres_sql(sql.strip(), True)
        try:
            with self._raw.cursor() as cur:
                cur.executemany(pg_sql, param_list)
                rc = int(cur.rowcount) if cur.rowcount is not None and cur.rowcount >= 0 else len(param_list)
            self._dirty_writes += max(1, rc)
            self._backend.bump_local_changes(max(1, rc))
            return PostgresCursorResult([], rowcount=rc, row_factory=self.row_factory, session=self)
        except Exception as exc:
            if (
                self._raw.info.transaction_status == pq.TransactionStatus.INERROR
                and not self._savepoints
                and self._dirty_writes == 0
            ):
                with contextlib.suppress(Exception):
                    self._raw.rollback()
            raise _wrap_pg_error(exc) from exc

    def executescript(self, script: str) -> PostgresCursorResult:
        from spaceinvasion.db.migrations import split_sql_statements

        last_res = PostgresCursorResult([], rowcount=0, row_factory=self.row_factory, session=self)
        for stmt in split_sql_statements(script):
            last_res = self.execute(stmt)
        return last_res

    def commit(self) -> None:
        try:
            self._raw.commit()
            if self._dirty_writes > 0:
                self._backend.notify_committed()
            self._dirty_writes = 0
            self._savepoints.clear()
        except Exception as exc:
            raise _wrap_pg_error(exc) from exc

    def rollback(self) -> None:
        try:
            self._raw.rollback()
            self._dirty_writes = 0
            self._savepoints.clear()
        except Exception as exc:
            raise _wrap_pg_error(exc) from exc

    def close(self) -> None:
        self._backend.close()

    # --- Catalog & PRAGMA Helpers ---

    def _table_exists(self, table_name: str) -> bool:
        with self._raw.cursor() as cur:
            cur.execute(
                """
                SELECT 1
                FROM pg_catalog.pg_tables
                WHERE schemaname = 'public' AND tablename = %s
                LIMIT 1
                """,
                (table_name.lower(),),
            )
            return cur.fetchone() is not None

    def _list_tables(self) -> list[str]:
        with self._raw.cursor() as cur:
            cur.execute(
                """
                SELECT tablename
                FROM pg_catalog.pg_tables
                WHERE schemaname = 'public' AND tablename != '_pg_pragma_meta'
                ORDER BY tablename ASC
                """
            )
            return [str(r[0]) for r in cur.fetchall()]

    def _read_table_info(self, table_name: str) -> list[tuple[int, str, str, int, Any, int]]:
        with self._raw.cursor() as cur:
            cur.execute(
                """
                SELECT
                    c.ordinal_position - 1 AS cid,
                    c.column_name AS name,
                    UPPER(c.data_type) AS type,
                    CASE WHEN c.is_nullable = 'NO' THEN 1 ELSE 0 END AS notnull,
                    c.column_default AS dflt_value,
                    CASE WHEN pk.column_name IS NOT NULL THEN 1 ELSE 0 END AS pk
                FROM information_schema.columns c
                LEFT JOIN (
                    SELECT kcu.column_name
                    FROM information_schema.table_constraints tc
                    JOIN information_schema.key_column_usage kcu
                      ON tc.constraint_name = kcu.constraint_name
                     AND tc.table_schema = kcu.table_schema
                     AND tc.table_name = kcu.table_name
                    WHERE tc.table_schema = 'public'
                      AND tc.table_name = %s
                      AND tc.constraint_type = 'PRIMARY KEY'
                ) pk ON pk.column_name = c.column_name
                WHERE c.table_schema = 'public'
                  AND c.table_name = %s
                ORDER BY c.ordinal_position ASC
                """,
                (table_name.lower(), table_name.lower()),
            )
            return [
                (int(r[0]), str(r[1]), str(r[2]), int(r[3]), r[4], int(r[5]))
                for r in cur.fetchall()
            ]

    def _ensure_pragma_table(self) -> None:
        with self._raw.cursor() as cur:
            cur.execute(
                """
                CREATE TABLE IF NOT EXISTS _pg_pragma_meta (
                    key TEXT PRIMARY KEY,
                    int_val BIGINT NOT NULL DEFAULT 0,
                    updated_ts DOUBLE PRECISION NOT NULL DEFAULT 0.0
                )
                """
            )

    def _read_user_version(self) -> int:
        if not self._table_exists("_pg_pragma_meta"):
            return 0
        with self._raw.cursor() as cur:
            cur.execute("SELECT int_val FROM _pg_pragma_meta WHERE key = 'user_version' LIMIT 1")
            row = cur.fetchone()
            return int(row[0] or 0) if row is not None else 0

    def _write_user_version(self, version: int) -> None:
        self._ensure_pragma_table()
        with self._raw.cursor() as cur:
            cur.execute(
                """
                INSERT INTO _pg_pragma_meta(key, int_val, updated_ts)
                VALUES ('user_version', %s, %s)
                ON CONFLICT(key) DO UPDATE SET
                    int_val = EXCLUDED.int_val,
                    updated_ts = EXCLUDED.updated_ts
                """,
                (int(version), round(time.time(), 3)),
            )
        self._dirty_writes += 1
        self._backend.bump_local_changes(1)

    def _run_integrity_check(self, *, full: bool = False) -> list[str]:
        try:
            with self._raw.cursor() as cur:
                cur.execute("SELECT 1")
                if full:
                    # Verify catalog visibility & non-invalid indexes in public schema
                    cur.execute(
                        """
                        SELECT i.relname
                        FROM pg_catalog.pg_index ix
                        JOIN pg_catalog.pg_class i ON i.oid = ix.indexrelid
                        JOIN pg_catalog.pg_namespace n ON n.oid = i.relnamespace
                        WHERE n.nspname = 'public' AND NOT ix.indisvalid
                        """
                    )
                    bad = [f"invalid_index:{r[0]}" for r in cur.fetchall()]
                    if bad:
                        return bad
            return ["ok"]
        except Exception as exc:
            return [f"error:{exc}"]


class PostgresSessionLock:
    """Re-entrant per-thread pooled connection scope replacing `threading.Lock()` in `GameDatabase`.

    Entering `with self._lock:` checks out a dedicated `psycopg.Connection` for the calling
    thread (reused across nested `with self._lock:` calls on the same thread) so multiple
    HTTP reader threads and background sweep/telemetry writers run concurrently via MVCC.
    """

    def __init__(self, backend: "PostgresPoolBackend") -> None:
        self._backend = backend

    def __enter__(self) -> PostgresSession:
        return self._backend._enter_thread_session()

    def __exit__(self, exc_type: Any, exc_val: Any, exc_tb: Any) -> None:
        self._backend._exit_thread_session(exc_type is not None)


class PostgresConnectionProxy:
    """Thread-local proxy exposing `sqlite3.Connection`-compatible methods on `GameDatabase._conn`."""

    def __init__(self, backend: "PostgresPoolBackend") -> None:
        self._backend = backend
        self.row_factory: Any = PostgresRow

    @property
    def total_changes(self) -> int:
        return self._backend.total_changes

    @property
    def in_transaction(self) -> bool:
        sess = self._backend._current_session()
        return sess.in_transaction if sess is not None else False

    def cursor(self) -> PostgresCursorResult:
        sess = self._backend._current_session()
        if sess is not None:
            sess.row_factory = self.row_factory
            return sess.cursor()
        raise sqlite3.ProgrammingError("cursor() requires an active session scope (`with db._lock:`).")

    def execute(self, sql: str, params: Optional[Sequence[Any]] = None) -> PostgresCursorResult:
        sess = self._backend._current_session()
        if sess is not None:
            sess.row_factory = self.row_factory
            return sess.execute(sql, params)
        with self._backend.session_lock as temp_sess:
            temp_sess.row_factory = self.row_factory
            res = temp_sess.execute(sql, params)
            if temp_sess._dirty_writes > 0:
                temp_sess.commit()
            return res

    def executemany(self, sql: str, seq_of_params: Iterable[Sequence[Any]]) -> PostgresCursorResult:
        sess = self._backend._current_session()
        if sess is not None:
            sess.row_factory = self.row_factory
            return sess.executemany(sql, seq_of_params)
        with self._backend.session_lock as temp_sess:
            temp_sess.row_factory = self.row_factory
            res = temp_sess.executemany(sql, seq_of_params)
            temp_sess.commit()
            return res

    def executescript(self, script: str) -> PostgresCursorResult:
        sess = self._backend._current_session()
        if sess is not None:
            sess.row_factory = self.row_factory
            return sess.executescript(script)
        with self._backend.session_lock as temp_sess:
            temp_sess.row_factory = self.row_factory
            res = temp_sess.executescript(script)
            temp_sess.commit()
            return res

    def commit(self) -> None:
        sess = self._backend._current_session()
        if sess is not None:
            sess.commit()

    def rollback(self) -> None:
        sess = self._backend._current_session()
        if sess is not None:
            sess.rollback()

    def close(self) -> None:
        self._backend.close()


class PostgresPoolBackend:
    """Thread-safe PostgreSQL connection pool manager (`psycopg_pool.ConnectionPool`)."""

    def __init__(
        self,
        dsn: str,
        *,
        min_size: int = 2,
        max_size: int = 16,
        connect_timeout: float = 8.0,
    ) -> None:
        self.dsn = str(dsn).strip()
        self._closed = False
        self._meta_lock = threading.Lock()
        self._total_changes = 0
        self._cached_data_ver: int = 0
        self._cached_data_ver_mono: float = 0.0
        self._tls = threading.local()

        def _configure_conn(conn: psycopg.Connection[Any]) -> None:
            conn.autocommit = False

        self._pool = ConnectionPool(
            conninfo=self.dsn,
            min_size=max(1, int(min_size)),
            max_size=max(2, int(max_size)),
            timeout=max(2.0, float(connect_timeout)),
            kwargs={"connect_timeout": max(2, int(round(connect_timeout)))},
            configure=_configure_conn,
            open=True,
        )
        self._pool.wait(timeout=max(3.0, float(connect_timeout)))
        self.session_lock = PostgresSessionLock(self)
        self.conn_proxy = PostgresConnectionProxy(self)

        with self.session_lock as sess:
            sess._ensure_pragma_table()
            sess.commit()

    @property
    def total_changes(self) -> int:
        return self._total_changes

    def bump_local_changes(self, delta: int = 1) -> None:
        with self._meta_lock:
            self._total_changes += max(1, int(delta))
            self._cached_data_ver_mono = 0.0

    def notify_committed(self) -> None:
        with self._meta_lock:
            self._cached_data_ver_mono = 0.0

    def get_data_version(self, raw_conn: Optional[psycopg.Connection[Any]] = None) -> int:
        now_m = time.monotonic()
        with self._meta_lock:
            if (now_m - self._cached_data_ver_mono) < 0.25 and self._cached_data_ver > 0:
                return self._cached_data_ver

        val = 0
        try:
            if raw_conn is not None and raw_conn.info.transaction_status != pq.TransactionStatus.INERROR:
                with raw_conn.cursor() as cur:
                    cur.execute("SELECT pg_snapshot_xmax(pg_current_snapshot())::text")
                    r = cur.fetchone()
                    val = int(str(r[0])) if r and r[0] is not None else 0
            else:
                with self._pool.connection() as c:
                    with c.cursor() as cur:
                        cur.execute("SELECT pg_snapshot_xmax(pg_current_snapshot())::text")
                        r = cur.fetchone()
                        val = int(str(r[0])) if r and r[0] is not None else 0
                    c.rollback()
        except Exception:
            val = self._total_changes

        with self._meta_lock:
            self._cached_data_ver = val
            self._cached_data_ver_mono = now_m
        return val

    def database_size_bytes(self) -> int:
        try:
            with self.session_lock as sess:
                row = sess.execute("SELECT pg_database_size(current_database())").fetchone()
                return int(row[0] or 0) if row is not None else 0
        except Exception:
            return 0

    def fast_table_counts(self, tables: Sequence[str], existing_tables: set[str]) -> dict[str, int]:
        """Fetch exact `COUNT(*)` across all requested tables in a single PostgreSQL round-trip."""
        present = [t for t in tables if t in existing_tables and _SAFE_IDENT_RE.match(t)]
        out: dict[str, int] = {t: 0 for t in tables}
        if not present:
            return out
        subqueries = ", ".join(f'(SELECT COUNT(*) FROM "{t}") AS "{t}"' for t in present)
        with self.session_lock as sess:
            row = sess.execute(f"SELECT {subqueries}").fetchone()
            if row is not None:
                for idx, t in enumerate(present):
                    out[t] = int(row[idx] or 0)
        return out

    def sync_identity_sequences(self, tables: Optional[Sequence[str]] = None) -> dict[str, int]:
        """Advance PostgreSQL `IDENTITY` sequences on `id` columns to `MAX(id)` after bulk imports."""
        target_tables = tuple(tables) if tables is not None else tuple(sorted(IDENTITY_ID_TABLES))
        synced: dict[str, int] = {}
        with self.session_lock as sess:
            existing = set(sess._list_tables())
            with sess._raw.cursor() as cur:
                for tbl in target_tables:
                    if tbl not in existing or not _SAFE_IDENT_RE.match(tbl):
                        continue
                    cur.execute(
                        "SELECT pg_get_serial_sequence(%s, 'id')",
                        (f'public."{tbl}"',),
                    )
                    seq_row = cur.fetchone()
                    seq_name = str(seq_row[0]) if seq_row and seq_row[0] else ""
                    if not seq_name:
                        continue
                    cur.execute(f'SELECT COALESCE(MAX(id), 0), COUNT(*) FROM "{tbl}"')
                    mx_row = cur.fetchone()
                    max_id = int(mx_row[0] or 0) if mx_row else 0
                    cnt = int(mx_row[1] or 0) if mx_row else 0
                    if cnt > 0 and max_id > 0:
                        cur.execute("SELECT setval(%s, %s, true)", (seq_name, max_id))
                    else:
                        cur.execute("SELECT setval(%s, 1, false)", (seq_name,))
                    synced[tbl] = max_id
            sess.commit()
        return synced

    def _current_session(self) -> Optional[PostgresSession]:
        return getattr(self._tls, "session", None)

    def _enter_thread_session(self) -> PostgresSession:
        if self._closed:
            raise sqlite3.ProgrammingError("PostgreSQL connection pool is closed.")
        depth = int(getattr(self._tls, "depth", 0))
        if depth > 0 and getattr(self._tls, "session", None) is not None:
            self._tls.depth = depth + 1
            return self._tls.session
        ctx = self._pool.connection()
        raw_conn = ctx.__enter__()
        sess = PostgresSession(self, raw_conn)
        self._tls.ctx = ctx
        self._tls.session = sess
        self._tls.depth = 1
        return sess

    def _exit_thread_session(self, had_exception: bool) -> None:
        depth = int(getattr(self._tls, "depth", 0))
        if depth <= 0:
            return
        if depth > 1:
            self._tls.depth = depth - 1
            return
        sess: Optional[PostgresSession] = getattr(self._tls, "session", None)
        ctx = getattr(self._tls, "ctx", None)
        self._tls.depth = 0
        self._tls.session = None
        self._tls.ctx = None
        try:
            if sess is not None:
                if had_exception or sess._raw.info.transaction_status in (
                    pq.TransactionStatus.INTRANS,
                    pq.TransactionStatus.INERROR,
                ):
                    with contextlib.suppress(Exception):
                        sess._raw.rollback()
        finally:
            if ctx is not None:
                ctx.__exit__(None, None, None)

    def close(self) -> None:
        with self._meta_lock:
            if self._closed:
                return
            self._closed = True
        with contextlib.suppress(Exception):
            self._pool.close()
