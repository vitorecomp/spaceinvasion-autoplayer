"""Pooled PostgreSQL adapter (`psycopg` v3 + `psycopg_pool`) compatible with `MigrationRunner` and `GameDatabase`.

Provides:
- `PostgresRow`: Dual positional (`row[0]`, tuple-unpacking) and mapping (`row['col']`, `dict(row)`) row wrapper.
- `translate_sqlite_to_postgres_sql`: Lexer-accurate SQLite -> PostgreSQL 16 SQL dialect translator (LRU-cached).
- `PostgresPoolBackend`: Thread-safe MVCC connection-pooled backend where `with db._lock:` checks out a per-thread
  pooled connection so concurrent readers and writers never serialize on a global database lock.
"""

