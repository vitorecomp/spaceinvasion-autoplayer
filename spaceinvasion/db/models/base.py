"""Declarative base and shared PostgreSQL column primitives for ORM models."""

from __future__ import annotations

from typing import ClassVar

from sqlalchemy import BigInteger, Double, Identity, Text
from sqlalchemy.orm import DeclarativeBase

_ScalarType = type[int] | type[float] | type[str]
_SqlType = type[BigInteger] | type[Double[float]] | type[Text]


class Base(DeclarativeBase):
    """Shared SQLAlchemy 2.0 declarative base for all PostgreSQL game tables."""

    type_annotation_map: ClassVar[dict[_ScalarType, _SqlType]] = {
        int: BigInteger,
        float: Double,
        str: Text,
    }


def identity_pk() -> Identity:
    """Return a PostgreSQL `GENERATED BY DEFAULT AS IDENTITY` definition."""
    return Identity(always=False)


__all__ = ["Base", "identity_pk"]
